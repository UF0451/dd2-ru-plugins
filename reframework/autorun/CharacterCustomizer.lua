local function IsCharacterEditTimerOff(characterIndex, character)
	if customizer.regenerateBeforeEditing then
		if (common.GetDelayTimerStatus(customizer.characterEditTimerName) == common.DELAYTIMERSTATUS.NONE or common.GetDelayTimerStatus(customizer.characterEditTimerName) == common.DELAYTIMERSTATUS.RUNNING) then
			return false
		elseif (common.GetDelayTimerStatus(customizer.characterEditTimerName) == common.DELAYTIMERSTATUS.OFF) then
			if character == nil then
				character = characterHelper.GetManagedCharacter(characterIndex, config)
			end
			if characterEditHelper.IsCharacterReadyToBeEdited(character) then
				customizer.isWeaponSet[characterIndex] = false
				return true
			else
				return false
			end
		end
		return false
	end
	return true
end

local function RegenerateThenEditCharacter(characterIndex) --, character)

	local character
	if ((config.enableCharacterEditForCharacter[tostring(characterIndex)] and not common.GetBooleanValue(customizer.isCharacterEdited[characterIndex])) or common.GetBooleanValue(customizer.reapplyEdits[characterIndex])) then --and character == nil then
		character = characterHelper.GetManagedCharacter(characterIndex, config)
	end

	if character then
		if not common.GetBooleanValue(customizer.appearanceHasNotChanged[characterIndex]) and (customizer.selectedEditTypeIndex[characterIndex] ~= characterEditHelper.CHARACTEREDITTYPE.NONE and customizer.selectedEditTypeIndex[characterIndex] ~= characterEditHelper.CHARACTEREDITTYPE.COSTUME) then
			if customizer.editLockCharacterInfo.CharacterIndex == nil then
				if (customizer.lastRegenerateTime[characterIndex] == nil or os.time() - customizer.lastRegenerateTime[characterIndex] > 7) and (customizer.lastEditEndTime[characterIndex] == nil or os.time() - customizer.lastEditEndTime[characterIndex] > 7) then
				--(character:get_IsInCamera() and characterHelper.IsNearPlayerCharacter(characterIndex, config, config.nearDistance, character))
					customizer.editLockCharacterInfo = {}
					customizer.editLockCharacterInfo.CharacterIndex = characterIndex
					customizer.editLockCharacterInfo.Character = character
					customizer.editLockCharacterInfo.CharacterName = characterHelper.GetManagedCharacterName(characterIndex, config, 2)
					common.DeleteDelayTimer(customizer.characterEditTimerName)
					characterHelper.RegenerateCharacterByCharacterIndex(characterIndex, config, character)
				end
			end
		elseif common.GetBooleanValue(customizer.appearanceHasNotChanged[characterIndex]) or customizer.selectedEditTypeIndex[characterIndex] == characterEditHelper.CHARACTEREDITTYPE.COSTUME then
			EditCharacter(characterIndex, character)
		end
	end

end

local function EditCharacters()

	local isAnyCharacterBeingRegenerated = false
	local closestCharacterDistance
	local priorityCharacterIndex = -2
	customizer.priorityCharacterName = "none"
	
	if customizer.regenerateBeforeEditing then
	
		for i = 0, characterHelper.GetFinalManagedCharacterIndex(config) do --characterHelper.GetPartyMembersFinalIndex(config) do --
			if ((config.enableCharacterEditForCharacter[tostring(i)] and not common.GetBooleanValue(customizer.isCharacterEdited[i])) or common.GetBooleanValue(customizer.reapplyEdits[i])) then
				local currentCharacterDistance = characterHelper.GetManagedCharacterDistanceFromPlayerCharacter(i, config, nil)
				if (customizer.editLockCharacterInfo.CharacterIndex ~= nil and customizer.editLockCharacterInfo.CharacterIndex == i) or closestCharacterDistance == nil or i == -1 then
					closestCharacterDistance = currentCharacterDistance
					priorityCharacterIndex = i
					if (customizer.editLockCharacterInfo.CharacterIndex ~= nil and customizer.editLockCharacterInfo.CharacterIndex == i) or i == -1 then
						isAnyCharacterBeingRegenerated = true
						break
					end
				elseif closestCharacterDistance ~= nil then
					if math.abs(currentCharacterDistance.total) < math.abs(closestCharacterDistance.total) then
						closestCharacterDistance = currentCharacterDistance
						priorityCharacterIndex = i
					end
				end
			end
		end
		
	end
	
	if priorityCharacterIndex > -2 then
		customizer.priorityCharacterName = characterHelper.GetManagedCharacterName(priorityCharacterIndex, config, 2)
	end

	for i = -1, characterHelper.GetFinalManagedCharacterIndex(config) do --characterHelper.GetPartyMembersFinalIndex(config) do --
	
		local character = characterHelper.GetManagedCharacter(i, config)

		if character and character:get_Valid() then
			if common.GetBooleanValue(customizer.shouldRefreshVariationStyles[i]) and customizer.refreshCharacterID == character.CharacterID and common.ChangeToDefaultIfNotANumber(customizer.shouldRefreshVariationStylesCountdown[i], 0) <= 0  then
				characterEditHelper.RefreshManagedCharacterCostumeVariationStyles(i, config, character)
				customizer.shouldRefreshVariationStyles[i] = false
			elseif common.GetBooleanValue(customizer.shouldRefreshVariationStyles) then
				customizer.shouldRefreshVariationStylesCountdown[i] = common.ChangeToDefaultIfNotANumber(customizer.shouldRefreshVariationStylesCountdown[i], 0) - 1
			end
		end
		
		if not isAnyCharacterBeingRegenerated or (customizer.editLockCharacterInfo.CharacterIndex ~= nil and customizer.editLockCharacterInfo.CharacterIndex == i)  then	
			
			if customizer.regenerateBeforeEditing and i > characterHelper.GetPartyMembersFinalIndex(config) then
				if customizer.editLockCharacterInfo.CharacterIndex == nil and i == priorityCharacterIndex then
					RegenerateThenEditCharacter(i) --, character)
				elseif customizer.editLockCharacterInfo.CharacterIndex == i then
					if IsCharacterEditTimerOff(customizer.editLockCharacterInfo.CharacterIndex, character) then
						EditCharacter(customizer.editLockCharacterInfo.CharacterIndex, character)
					end
				end
			else
				EditCharacter(i, character)
			end
			
			--if customizer.editLockCharacterInfo.CharacterIndex then
			--	if customizer.editLockCharacterInfo.CharacterIndex == i and not characterHelper.IsNearPlayerCharacter(customizer.editLockCharacterInfo.CharacterIndex, config, config.nearDistance + 1, character) then
			--		ReleaseEditLock()
			--	end
			--end
			
		else
		
			if (config.enableCharacterEditForCharacter[tostring(i)] 
			and (customizer.editLockCharacterInfo.CharacterIndex == nil or customizer.editLockCharacterInfo.CharacterIndex == i)
			and not character)
			then
				characterEditHelper.repc()
				customizer.isCharacterEdited[i] = false
				--customizer.isCloneOrMockupEdited[i] = false
				customizer.isWeaponSet[i] = false
				customizer.isMeshUpdated[i] = false
			end
			
		end

		if (not config.enableCharacterEditForCharacter[tostring(i)]
		and not character)
		then
			customizer.isCharacterEdited[i] = false
			--customizer.isCloneOrMockupEdited[i] = false
			customizer.isWeaponSet[i] = false
			customizer.isMeshUpdated[i] = false
		end
			
		if (config.autoEquipWeapon[tostring(i)] or customizer.reapplyWeaponEdits[i]) and not customizer.isWeaponSet[i] then
			characterEditHelper.SetWeaponsFromWeaponOptions(i, config.weaponDetails[tostring(i)], config, nil, nil)
			customizer.reapplyWeaponEdits[i] = false
			customizer.isWeaponSet[i] = true
			customizer.isMeshUpdated[i] = false
		end

		if (config.autoReapplyMesh[tostring(i)] or customizer.reapplyMeshEdits[i]) and not customizer.isMeshUpdated[i] then
			if character then
				if customizer.meshEditDelayTime[i] <= 0 or customizer.reapplyMeshEdits[characterIndex] then
					if characterEditHelper.IsMeshIDNamesChanged(config.characterObjectMeshDetails[tostring(i)]) then
						characterEditHelper.SwapCostumePartSwapper(character, i, nil, nil, config.characterObjectMeshDetails[tostring(i)], config)
					else
						characterEditHelper.SetAllCharacterObjectMeshDetails(character, config.characterObjectMeshDetails[tostring(i)], nil, nil)
					end
					customizer.reapplyMeshEdits[i] = false
					customizer.isMeshUpdated[i] = true
					customizer.meshEditDelayTime[i] = customizer.originalMeshEditDelayTime
				else
					customizer.meshEditDelayTime[i] = customizer.meshEditDelayTime[i] - 1
				end
			end
		end
		
	end

end

