				and (customizer.selectedEditTypeIndex[characterIndex] == characterEditHelper.CHARACTEREDITTYPE.ALL
				or customizer.selectedEditTypeIndex[characterIndex] == characterEditHelper.CHARACTEREDITTYPE.COSTUME)
				then
				local modDetails = {}
				modDetails.isLockedForSpecificCharacter = true
				modDetails.SkipRequestSwap = false
				if not isEditCharacterInterrupted and character and not common.GetBooleanValue(customizer.isCharacterEdited[characterIndex]) then
					local costumeEditWasSuccessful = characterEditHelper.ApplyCostumeFromCostumeOptions(characterIndex, config.costumeDetails[tostring(characterIndex)], config, modDetails, nil)
					lastEditWasSuccessful = lastEditWasSuccessful and costumeEditWasSuccessful
				end
				--if cloneOrMockupBuilderDetails and not common.GetBooleanValue(customizer.isCloneOrMockupEdited[characterIndex]) then
				--	characterEditHelper.ApplyCostumeFromCostumeOptions(characterIndex, config.costumeDetails[tostring(characterIndex)], config, modDetails, cloneOrMockupBuilderDetails.cloneOrMockupBuilder)
				--end
			end
				
			--end
			
			UpdateEditStatus(characterIndex, characterEditDataSource)
		
			if config.enableTransmogOnStatusScreens and (lastEditWasSuccessful and characterIndex <= characterHelper.GetPartyMembersFinalIndex(config)) then
				characterEditHelper.RefreshMockupAndMockupFace(characterIndex, config, nil, nil)
			end

			if not isEditCharacterInterrupted and character then
				customizer.isCharacterEdited[characterIndex] = true
				customizer.reapplyEdits[characterIndex] = false
				customizer.editLockCharacterInfo = {}
				if (config.autoReapplyMesh[tostring(characterIndex)] or customizer.reapplyMeshEdits[characterIndex]) and not customizer.isMeshUpdated[characterIndex] then
					characterEditHelper.ResetCostumeMeshID(character, config.characterObjectMeshDetails[tostring(characterIndex)], "ALL")
				end
				config.characterObjectMeshDetails[tostring(characterIndex)] = characterEditHelper.GetDefaultCharacterObjectMeshDetails()
				customizer.isMeshUpdated[characterIndex] = false
			end
			--if cloneOrMockupBuilderDetails then
			--	customizer.isCloneOrMockupEdited[characterIndex] = true
			--	customizer.reapplyEditsToCloneOrMockup[characterIndex] = false
			--end

		end
		
		if not isEditCharacterInterrupted and customizer.regenerateBeforeEditing and characterIndex <= characterHelper.GetPartyMembersFinalIndex(config) and customizer.selectedEditTypeIndex[characterIndex] ~= characterEditHelper.CHARACTEREDITTYPE.COSTUME then
			characterHelper.RegenerateCharacterByCharacterIndex(characterIndex, config, character)
		end

		if lastEditWasSuccessful then
			SaveCostumeVariationStylesToCache(character, characterIndex)
			if character then
				customizer.refreshCharacterID = character.CharacterID
			else
				customizer.refreshCharacterID = ""
			end
			customizer.shouldRefreshVariationStyles[characterIndex] = true
			customizer.shouldRefreshVariationStylesCountdown[characterIndex] = customizer.shouldRefreshVariationStylesCountdownStart
		end
		
	end

end

