			else
				characterManagerData = common.GetDataTableFromFile(characterManagerName, config.characterFilesFolderName, false)
			end
			if characterManagerData then
				if not isEditCharacterInterrupted and character and not common.GetBooleanValue(customizer.isCharacterEdited[characterIndex]) then
					characterEditDataSource.additionalParameters = additionalParameters
					characterEditDataSource.characterCustomizationData = customizer.characterCustomizationData[characterIndex]
					characterEditDataSource.characterManagerData = characterManagerData
					characterEditDataSource.npcCharacterDetails = nil
				end
			end
		else
			local npcCharacterDetails = characterHelper.GetCharacterDetailsByCharacterIDName(config.npcCharID2[tostring(characterIndex)])
			characterEditDataSource.characterManagerName = ""
			characterEditDataSource.characterCustomizationData = nil
			characterEditDataSource.characterManagerData = nil
			characterEditDataSource.npcCharacterDetails = npcCharacterDetails
		end
	end

	characterEditDataSource.additionalParameters = additionalParameters
	
	return characterEditDataSource
	
end

local function UpdateEditStatus(characterIndex, characterEditDataSource)	

	if characterEditDataSource and characterEditDataSource.currentSelectedEditTypeIndex ~= characterEditHelper.CHARACTEREDITTYPE.NONE then		
			
		local copySourceText = ""
		
		if characterEditDataSource then
