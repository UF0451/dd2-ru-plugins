local function RefreshSelectedDataTables()
	if customizer.currentRefreshCharacterIndex <= characterHelper.GetFinalManagedCharacterIndex(config) and customizer.refreshSelectedDataTablesCountdown == 0 then
		if customizer.currentRefreshCharacterIndex == -1 then
			print("Character Customizer: Loading Character data files into the cache.\nThis might while to complete depending on the number of files\nyou have currently selected as data source.. " .. tostring(os.date("%Y-%m-%d %H:%M:%S", os.time())))
		end
		common.SetIsFileDataTableLoaded(config.characterFilesFolderName, config.characterManagerComboBoxValue[tostring(customizer.currentRefreshCharacterIndex)], false)
		common.GetDataTableFromFile(config.characterManagerComboBoxValue[tostring(customizer.currentRefreshCharacterIndex)], config.characterFilesFolderName, false)
		customizer.currentRefreshCharacterIndex = customizer.currentRefreshCharacterIndex + 1
		customizer.refreshSelectedDataTablesCountdown = customizer.refreshSelectedDataTablesCountdownStart
		if customizer.currentRefreshCharacterIndex == characterHelper.GetFinalManagedCharacterIndex(config) then
			print("Character Customizer: Done loading Character data files. " .. tostring(os.date("%Y-%m-%d %H:%M:%S", os.time())))
			customizer.refreshSelectedDataTables = false
			customizer.currentRefreshCharacterIndex = -1
		end
	end
	if customizer.refreshSelectedDataTablesCountdown > 0 then
		customizer.refreshSelectedDataTablesCountdown = customizer.refreshSelectedDataTablesCountdown - 1
	end
end

