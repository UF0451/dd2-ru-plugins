local previousConfig
local config

local function ReadConfig()

	previousConfig = json.load_file(configFileName)
	defaultConfig = GetDefaultConfig()
	config = defaultConfig

	if previousConfig then

		config.modEnabled = common.GetBooleanValue(previousConfig.modEnabled)
		config.originalChildWindowPosition = common.ChangeToDefaultIfNil(previousConfig.originalChildWindowPosition, defaultConfig.originalChildWindowPosition)
		originalChildWindowPositionIndex = common.GetCurrentListIndex(common.WINDOWPOSITIONS, config.originalChildWindowPosition)

		config.characterFilesFolderName = common.ChangeToDefaultIfNil(previousConfig.characterFilesFolderName, config.characterFilesFolderName)
		config.useNamesAsLabels = common.GetBooleanValue(previousConfig.useNamesAsLabels)
		config.removeUnknownGenderStyles = common.GetBooleanValue(previousConfig.removeUnknownGenderStyles)
		config.maxManagedNPCCount = common.ChangeToDefaultIfNotANumber(previousConfig.maxManagedNPCCount, defaultConfig.maxManagedNPCCount)
		config.refreshListsWhenPausedGUI = common.GetBooleanValue(previousConfig.refreshListsWhenPausedGUI)
		config.enableTransmogOnStatusScreens = common.GetBooleanValue(previousConfig.enableTransmogOnStatusScreens)
		
		if config.version ~= previousConfig.version then
			config.nearDistance = nearDistanceDefault
			config.npcWaitTimeAfterRegenerate = npcWaitTimeAfterRegenerateDefault
			config.partyWaitTimeAfterRegenerate = partyWaitTimeAfterRegenerateDefault
			config.applyWorkarounds = true
		else
			config.nearDistance = common.ChangeToDefaultIfNotANumber(previousConfig.nearDistance, defaultConfig.nearDistance)
			config.npcWaitTimeAfterRegenerate = common.ChangeToDefaultIfNotANumber(previousConfig.npcWaitTimeAfterRegenerate, defaultConfig.npcWaitTimeAfterRegenerate)
			config.partyWaitTimeAfterRegenerate = common.ChangeToDefaultIfNotANumber(previousConfig.partyWaitTimeAfterRegenerate, defaultConfig.partyWaitTimeAfterRegenerate)
			config.applyWorkarounds = common.ChangeToDefaultIfNil(previousConfig.applyWorkarounds, true)
		end

		config.applyCustomizationScreenWorkarounds = common.ChangeToDefaultIfNil(previousConfig.applyCustomizationScreenWorkarounds, true)

		characterHelper.InitializeCharacterHelper(config, 4, config.maxManagedNPCCount, config.refreshListsWhenPausedGUI)
		tempMaxNPCCount = config.maxManagedNPCCount

		for i = -1, characterHelper.GetFinalManagedCharacterIndex(config) do
		
			config.enableCharacterEditForCharacter[tostring(i)] = common.GetBooleanValue(common.GetListItem(previousConfig.enableCharacterEditForCharacter, tostring(i)))
			config.autoEquipWeapon[tostring(i)] = common.GetBooleanValue(common.GetListItem(previousConfig.autoEquipWeapon, tostring(i)))
			config.autoReapplyMesh[tostring(i)] = common.GetBooleanValue(common.GetListItem(previousConfig.autoReapplyMesh, tostring(i)))
			config.characterManagerComboBoxValue[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.characterManagerComboBoxValue, tostring(i)), "")
			config.selectedEditTypeValue[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.selectedEditTypeValue, tostring(i)), defaultConfig.selectedEditTypeValue[tostring(0)])
			
			config.npcCharID[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.npcCharID, tostring(i)), "")
			config.npcCharID2[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.npcCharID2, tostring(i)), "")
			config.appearanceID[tostring(i)] = common.ChangeToDefaultIfNotANumber(common.GetListItem(previousConfig.appearanceID, tostring(i)), defaultConfig.appearanceID[tostring(0)])
			config.costumeID[tostring(i)] = common.ChangeToDefaultIfNotANumber(common.GetListItem(previousConfig.costumeID, tostring(i)), defaultConfig.costumeID[tostring(0)])
			config.costumeSourceIndex[tostring(i)] = common.ChangeToDefaultIfNotANumber(common.GetListItem(previousConfig.costumeSourceIndex, tostring(i)), defaultConfig.costumeSourceIndex[tostring(0)])
			config.costumeOptionsPresetName[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.costumeOptionsPresetName, tostring(i)), "")
			config.costumeDetails[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.costumeDetails, tostring(i)), characterEditHelper.GetDefaultCostumeDetails())
			config.costumeVariationStylesDetails[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.costumeVariationStylesDetails, tostring(i)), characterEditHelper.GetDefaultCostumeVariationStyleDetails())
			config.substituteName[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.substituteName, tostring(i)), "")
			config.weaponOptionsPresetName[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.weaponOptionsPresetName, tostring(i)), "")
			config.weaponDetails[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.weaponDetails, tostring(i)), characterEditHelper.GetDefaultWeaponDetails())
			config.meshOptionsPresetName[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.meshOptionsPresetName, tostring(i)), "")
			config.characterObjectMeshDetails[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.characterObjectMeshDetails, tostring(i)), characterEditHelper.GetDefaultCharacterObjectMeshDetails())

			config.characterCustomizerPresetName[tostring(i)] = common.ChangeToDefaultIfNil(common.GetListItem(previousConfig.characterCustomizerPresetName, tostring(i)), "")

		end
		
	else

		characterHelper.InitializeCharacterHelper(config, 4, config.maxManagedNPCCount, config.refreshListsWhenPausedGUI)
		tempMaxNPCCount = config.maxManagedNPCCount

	end

	customizer.characterCustomizerPresetsFolderName = characterEditHelper.filesList.mainFolderName .. "\\\\" .. modname .. "Presets"

	common.RefreshFileNamesList(config.characterFilesFolderName)
	common.RefreshFileNamesList(customizer.characterCustomizerPresetsFolderName)
	characterHelper.RefreshManagedCharacterCache(config)
	customizer.refreshSelectedDataTables = true

	for i = -1, characterHelper.GetFinalManagedCharacterIndex(config) do

		customizer.selectedEditTypeIndex[i] = common.GetCurrentListIndex(characterEditHelper.CHARACTEREDITTYPES, config.selectedEditTypeValue[tostring(i)])
		customizer.characterManagerComboBoxIndex[i] = common.GetCurrentListIndex(common.GetFileNamesList(config.characterFilesFolderName), config.characterManagerComboBoxValue[tostring(i)])
		customizer.tempSubstituteName[i] = common.ChangeToDefaultIfNil(config.substituteName[tostring(i)], "")		
		
		customizer.appearanceHasNotChanged[i] = false
		
		customizer.addCostumeSearchTextBoxes[i] = false
		customizer.addCostumeIDOverrideTextBoxes[i] = false
		customizer.addWeaponSearchTextBoxes[i] = false
		customizer.addWeaponIDOverrideTextBoxes[i] = false

		customizer.costumeOptionsFileExists[i] = false
		customizer.costumeOptionsShouldConfirmDelete[i] = false
		customizer.costumeOptionsNewPresetName[i] = ""
		customizer.weaponOptionsFileExists[i] = false
		customizer.weaponOptionsShouldConfirmDelete[i] = false
		customizer.weaponOptionsNewPresetName[i] = ""
		customizer.meshOptionsFileExists[i] = false
		customizer.meshOptionsShouldConfirmDelete[i] = false
		customizer.meshOptionsNewPresetName[i] = ""

		customizer.reapplyEdits[i] = false
		customizer.reapplyWeaponEdits[i] = false
		customizer.reapplyMeshEdits[i] = false

		customizer.selectedCharacterMeshIndex[i] = 1
		customizer.costumeUIInitialized[i] = false
		customizer.weaponUIInitialized[i] = false
		customizer.meshUIInitialized[i] = false

		customizer.isCharacterEdited[i] = false
		--customizer.isCloneOrMockupEdited[i] = false
		customizer.isWeaponSet[i] = false
		customizer.isMeshUpdated[i] = false
		customizer.meshEditDelayTime[i] = customizer.originalMeshEditDelayTime

		customizer.characterCustomizerNewPresetName[i] = ""
		customizer.characterCustomizerPresetFileExists[i] = false
		customizer.characterCustomizerPresetShouldConfirmDelete[i] = false
			
	end
	
end

