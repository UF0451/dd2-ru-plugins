local function GetCharacterSwapItemDetails(partSwapper, isSub, meshName, subMeshName)
	local swapItem
	--if customizer.Initialized then
		local characterIndex
		local currentMeshName = meshName
		if isSub and subMeshName and subMeshName ~= "" then
			currentMeshName = subMeshName
		end
		swapItem, characterIndex = characterEditHelper.GetCharacterSwapItem(config, partSwapper, currentMeshName, nil, nil)
		if characterIndex == nil then
			swapItem = nil
		else
			customizer.reapplyMeshEdits[characterIndex] = true
			customizer.isMeshUpdated[characterIndex] = false
		end
		local swapItemDetails
		if characterIndex then
			swapItemDetails = {}
			swapItemDetails.swapItem = swapItem
			swapItemDetails.characterIndex = characterIndex
			swapItemDetails.currentMeshName = currentMeshName
		end
		common.SetHookStorageValue("swapItemDetails", swapItemDetails)
	--end
	return swapItem
end

local function RefreshMeshDetails(retval)
	if config.modEnabled and customizer.Initialized then
		local swapItemDetails = common.GetHookStorageValue("swapItemDetails")
		if swapItemDetails then
			local character = characterHelper.GetManagedCharacter(swapItemDetails.characterIndex, config)
			local activeMockupDetails = common.GetActiveMockupDetails()
			if character then
				if activeMockupDetails.MockupBuilder or activeMockupDetails.MockupCtrl then
					if config.enableTransmogOnStatusScreens then
						characterEditHelper.AddCORMOM(modname, 3, config, character, swapItemDetails.characterIndex, activeMockupDetails.MockupBuilder, activeMockupDetails.MockupCtrl, config.characterObjectMeshDetails[tostring(swapItemDetails.characterIndex)], customizer.selectedCharacterMeshIndex[swapItemDetails.characterIndex])
					end
				end
				characterEditHelper.AddCORMOM(modname, 3, config, character, swapItemDetails.characterIndex, nil, nil, config.characterObjectMeshDetails[tostring(swapItemDetails.characterIndex)], customizer.selectedCharacterMeshIndex[swapItemDetails.characterIndex])
			end
		end
	end
	return retval
end

