				lastEditAppearanceID = config.appearanceID[tostring(characterIndex)]
				lastEditCostumeID = config.costumeID[tostring(characterIndex)]
				lastEditEditType = characterEditHelper.CHARACTEREDITTYPES[customizer.selectedEditTypeIndex[characterIndex]]
				if lastEditWasSuccessful then
					lastSuccessfulEditCharacter = lastEditCharacter
					lastSuccessfulEditAppearanceID = lastEditAppearanceID
					lastSuccessfulEditCostumeID = lastEditCostumeID
					lastSuccessfulEditEditType = lastEditEditType
					lastSuccessfulEditTime = lastEditTime
				end
			else
				local npcName = ""
				if characterEditDataSource.npcCharacterDetails then
					npcName = characterEditDataSource.npcCharacterDetails.CharacterName
				else
					npcName = characterHelper.GetNPCName(config.npcCharID2[tostring(characterIndex)])
				end
				copySourceText = npcName .. " (NPC)"
				lastEditCharacter = "[" .. characterEditDataSource.characterName .. "] " .. copySourceText
				lastEditAppearanceID = 0
				lastEditCostumeID = 0
				lastEditEditType = characterEditHelper.CHARACTEREDITTYPES[customizer.selectedEditTypeIndex[characterIndex]]
				if lastEditWasSuccessful then
					lastSuccessfulEditCharacter = lastEditCharacter
					lastSuccessfulEditAppearanceID = lastEditAppearanceID
					lastSuccessfulEditCostumeID = lastEditCostumeID
					lastSuccessfulEditEditType = lastEditEditType
				end
			end
		end
	end

	if config.costumeSourceIndex[tostring(characterIndex)] == characterEditHelper.COSTUMESOURCE.COSTUMEOPTIONS
		and (customizer.selectedEditTypeIndex[characterIndex] == characterEditHelper.CHARACTEREDITTYPE.ALL
		or customizer.selectedEditTypeIndex[characterIndex] == characterEditHelper.CHARACTEREDITTYPE.COSTUME)
		then
		if customizer.selectedEditTypeIndex[characterIndex] == characterEditHelper.CHARACTEREDITTYPE.COSTUME then
			lastEditCharacter = "[" .. characterEditDataSource.characterName .. "], (Costume options)"
		else
			lastEditCharacter = lastEditCharacter .. " + (Costume options)"
		end
		lastEditCostumeID = 0
		if lastEditWasSuccessful then
				lastSuccessfulEditCharacter = lastEditCharacter
				lastSuccessfulEditCostumeID = lastEditCostumeID
		end
	end
	
	lastEditTime = tostring(os.date("%Y-%m-%d %H:%M:%S", os.time()))
	if lastEditWasSuccessful then
		lastSuccessfulEditTime = lastEditTime
	end
	
	customizer.appearanceHasNotChanged[characterIndex] = false
	customizer.lastEditEndTime[characterIndex] = os.time()

end

