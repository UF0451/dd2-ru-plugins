local function GetCharacterEditDataSource(characterIndex, character)

	local characterEditDataSource

	local isNPCSource = config.npcCharID2[tostring(characterIndex)] ~= ""
	
	if character == nil then
		character = characterHelper.GetManagedCharacter(characterIndex, config)
	end

	local characterName = characterHelper.GetManagedCharacterName(characterIndex, config)
	if characterName == "" then
		characterName = characterHelper.GetManagedCharacterLabel(characterIndex, config)			
	end
	
	local currentSelectedEditTypeIndex = customizer.selectedEditTypeIndex[characterIndex]

	if customizer.appearanceHasNotChanged[characterIndex] then
		currentSelectedEditTypeIndex = characterEditHelper.CHARACTEREDITTYPE.COSTUME
	end
	
	if config.costumeSourceIndex[tostring(characterIndex)] == characterEditHelper.COSTUMESOURCE.COSTUMEOPTIONS then
		if currentSelectedEditTypeIndex == characterEditHelper.CHARACTEREDITTYPE.ALL then
			currentSelectedEditTypeIndex = characterEditHelper.CHARACTEREDITTYPE.ALLEXCEPTCOSTUME
		elseif currentSelectedEditTypeIndex == characterEditHelper.CHARACTEREDITTYPE.COSTUME then
			currentSelectedEditTypeIndex = characterEditHelper.CHARACTEREDITTYPE.NONE
		end
	end
	
	characterEditDataSource = {}
	characterEditDataSource.characterName = characterName
	characterEditDataSource.isNPCSource = isNPCSource
	characterEditDataSource.currentSelectedEditTypeIndex = currentSelectedEditTypeIndex

	local additionalParameters = {}
	additionalParameters.config = config
	additionalParameters.editContexts = true
	additionalParameters.saveContext = true
	additionalParameters.npcCharID = config.npcCharID2[tostring(characterIndex)]
	additionalParameters.applyWorkarounds = config.applyWorkarounds
	additionalParameters.fixCode = 1

	if currentSelectedEditTypeIndex ~= characterEditHelper.CHARACTEREDITTYPE.NONE then
		if common.GetBooleanValue(customizer.ccss[characterIndex]) or not isNPCSource then
			local characterManagerName = config.characterManagerComboBoxValue[tostring(characterIndex)]
			characterEditDataSource.characterManagerName = characterManagerName
			local characterManagerData
			if common.GetBooleanValue(customizer.ccss[characterIndex]) then
				if not customizer.characterCustomizationData[characterIndex] then
					return characterEditDataSource
				end
				additionalParameters.doNotParseColors = true
				additionalParameters.isUsingEditValueArray = true
				additionalParameters.isCCDOnCCS = false
				additionalParameters.fixCode = 2
				characterManagerData = {}
				characterManagerData["HeadFaceEditor._Context"] = customizer.characterCustomizationData[characterIndex]["HeadFaceEditor"]
				characterManagerData["BodyEditor._BodyEditContext"] = customizer.characterCustomizationData[characterIndex]["BodyEditorBodyEdit"]
				characterManagerData["BodyEditor._PretenderContext"] = customizer.characterCustomizationData[characterIndex]["BodyEditorPretender"]
				characterManagerData["PartSwapper._HumanContext"] = customizer.characterCustomizationData[characterIndex]["PartSwapperHuman"]
				characterManagerData["BodyDetailEditor._Context"] = customizer.characterCustomizationData[characterIndex]["BodyDetailEditor"]
